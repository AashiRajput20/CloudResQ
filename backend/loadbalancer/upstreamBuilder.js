// Decides WHO is in the traffic pool and builds the Nginx upstream config. No Docker, no database.
const { instanceNumber } = require('../recovery/instanceNaming');

const byNumber = (a, b) =>
  instanceNumber(a.instanceName) - instanceNumber(b.instanceName) || a.instanceName.localeCompare(b.instanceName);

// containers = docker containers of the service ({ instanceName, name, state })
// instances  = MongoDB Instance records ({ instanceName, status, inTraffic })
function classify(containers, instances) {
  const byName = new Map(instances.map((i) => [i.instanceName, i]));
  const pool = [];
  const excluded = [];

  for (const c of containers) {
    const inst = byName.get(c.instanceName);
    let reason = null;
    if (c.state !== 'running') reason = `container ${c.state}`;
    else if (!inst) reason = 'not monitored yet';
    else if (inst.status === 'RECOVERING') reason = 'being recovered';
    else if (inst.status === 'UNHEALTHY' || inst.status === 'FAILED') reason = `unhealthy (${inst.status})`;
    else if (inst.inTraffic === false) reason = 'removed from traffic';

    if (reason) excluded.push({ instanceName: c.instanceName, reason });
    else pool.push({ instanceName: c.instanceName, host: c.name }); // host = container name (Docker DNS)
  }
  return { pool: pool.sort(byNumber), excluded: excluded.sort(byNumber) };
}

// max_fails=0: Nginx never removes a server by itself. Only CloudResQ decides.
function buildUpstreamConfig(pool, port) {
  const lines = pool.length
    ? pool.map((s) => `    server ${s.host}:${port} max_fails=0;  # ${s.instanceName}`)
    : ['    server 127.0.0.1:1 down;  # empty pool: Nginx answers 502'];
  return [
    '# Generated by CloudResQ. Do not edit by hand.',
    `# Active servers: ${pool.length}`,
    'upstream cloudresq_backend {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

module.exports = { classify, buildUpstreamConfig };